-- ============================================================================
--  TalkArena -- AP Capstone database schema (checkpoint CP2)
--  Team T0122 | PostgreSQL 15 or newer
--  Derived from dbms/01_normalization.md: 11 tables, all in BCNF.
--  Runs top-to-bottom on an empty database.
-- ============================================================================

DROP TABLE IF EXISTS fact_checks, video_participants, video_sessions,
    messages, room_ai_persona, room_members, rooms, ai_personas,
    topics, discussion_modes, users CASCADE;

-- ----------------------------------------------------------------------------
-- 1. users -- one row per person. handle, email are candidate keys.
-- ----------------------------------------------------------------------------
CREATE TABLE users (
    user_id        BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    handle         VARCHAR(30)  NOT NULL UNIQUE,
    email          VARCHAR(255) NOT NULL UNIQUE,
    full_name      VARCHAR(100) NOT NULL,
    password_hash  TEXT         NOT NULL,
    created_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    is_active      BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT users_handle_format CHECK (handle ~ '^[A-Za-z0-9_]{3,30}$'),
    CONSTRAINT users_email_format  CHECK (email ~ '^[^@\s]+@[^@\s]+\.[^@\s]+$')
);

-- ----------------------------------------------------------------------------
-- 2. discussion_modes -- small closed list: Movie Talk, Study Mode, Debate, ...
-- ----------------------------------------------------------------------------
CREATE TABLE discussion_modes (
    mode_id      BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mode_name    VARCHAR(40)  NOT NULL UNIQUE,
    description  TEXT         NOT NULL,
    CONSTRAINT discussion_modes_name_nonblank CHECK (length(btrim(mode_name)) > 0)
);

-- ----------------------------------------------------------------------------
-- 3. topics -- the subject of a room, with its category (topic -> category).
-- ----------------------------------------------------------------------------
CREATE TABLE topics (
    topic_id     BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    topic_name   VARCHAR(100) NOT NULL UNIQUE,
    category     VARCHAR(50)  NOT NULL,
    CONSTRAINT topics_name_nonblank CHECK (length(btrim(topic_name)) > 0)
);

-- ----------------------------------------------------------------------------
-- 4. ai_personas -- each persona is built for exactly one discussion mode.
-- ----------------------------------------------------------------------------
CREATE TABLE ai_personas (
    persona_id     BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    persona_name   VARCHAR(60)  NOT NULL,
    mode_id        BIGINT       NOT NULL,
    model_name     VARCHAR(60)  NOT NULL,
    system_prompt  TEXT         NOT NULL,
    CONSTRAINT ai_personas_mode_fk
        FOREIGN KEY (mode_id) REFERENCES discussion_modes (mode_id) ON DELETE RESTRICT
);

-- ----------------------------------------------------------------------------
-- 5. rooms -- a discussion room. The room's mode and topic are stored here
--    once (not per message).
-- ----------------------------------------------------------------------------
CREATE TABLE rooms (
    room_id       BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_name     VARCHAR(100) NOT NULL,
    invite_code   VARCHAR(12)  NOT NULL UNIQUE,
    host_user_id  BIGINT       NOT NULL,
    topic_id      BIGINT       NOT NULL,
    mode_id       BIGINT       NOT NULL,
    ai_enabled    BOOLEAN      NOT NULL DEFAULT FALSE,
    status        VARCHAR(10)  NOT NULL DEFAULT 'ACTIVE',
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    ended_at      TIMESTAMPTZ,
    CONSTRAINT rooms_host_fk
        FOREIGN KEY (host_user_id) REFERENCES users (user_id) ON DELETE RESTRICT,
    CONSTRAINT rooms_topic_fk
        FOREIGN KEY (topic_id) REFERENCES topics (topic_id) ON DELETE RESTRICT,
    CONSTRAINT rooms_mode_fk
        FOREIGN KEY (mode_id) REFERENCES discussion_modes (mode_id) ON DELETE RESTRICT,
    CONSTRAINT rooms_status_check CHECK (status IN ('ACTIVE', 'ENDED')),
    -- a room has an end time exactly when it has ended
    CONSTRAINT rooms_ended_iff_status CHECK ((status = 'ENDED') = (ended_at IS NOT NULL)),
    CONSTRAINT rooms_ended_after_created CHECK (ended_at IS NULL OR ended_at >= created_at),
    CONSTRAINT rooms_name_nonblank CHECK (length(btrim(room_name)) > 0)
);

-- ----------------------------------------------------------------------------
-- 6. room_members -- M:N between users and rooms. Key = (room_id, user_id).
-- ----------------------------------------------------------------------------
CREATE TABLE room_members (
    room_id    BIGINT       NOT NULL,
    user_id    BIGINT       NOT NULL,
    role       VARCHAR(10)  NOT NULL,
    joined_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    left_at    TIMESTAMPTZ,
    CONSTRAINT room_members_pkey PRIMARY KEY (room_id, user_id),
    CONSTRAINT room_members_room_fk
        FOREIGN KEY (room_id) REFERENCES rooms (room_id) ON DELETE CASCADE,
    CONSTRAINT room_members_user_fk
        FOREIGN KEY (user_id) REFERENCES users (user_id) ON DELETE CASCADE,
    CONSTRAINT room_members_role_check CHECK (role IN ('HOST', 'MEMBER')),
    CONSTRAINT room_members_left_after_joined
        CHECK (left_at IS NULL OR left_at >= joined_at)
);

-- ----------------------------------------------------------------------------
-- 7. room_ai_persona -- which AI persona is active in a room (M:N).
--    Rule "one persona per room" (room_id, mode_id -> persona_id) is enforced
--    by the trigger below, because a single-row CHECK cannot see other rows.
-- ----------------------------------------------------------------------------
CREATE TABLE room_ai_persona (
    room_id     BIGINT NOT NULL,
    persona_id  BIGINT NOT NULL,
    CONSTRAINT room_ai_persona_pkey PRIMARY KEY (room_id, persona_id),
    CONSTRAINT room_ai_persona_room_fk
        FOREIGN KEY (room_id) REFERENCES rooms (room_id) ON DELETE CASCADE,
    CONSTRAINT room_ai_persona_persona_fk
        FOREIGN KEY (persona_id) REFERENCES ai_personas (persona_id) ON DELETE RESTRICT
);

CREATE OR REPLACE FUNCTION check_room_ai_persona() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    -- 1. the persona's mode must equal the room's mode
    IF NOT EXISTS (
        SELECT 1
        FROM rooms r
        JOIN ai_personas p ON p.mode_id = r.mode_id
        WHERE r.room_id = NEW.room_id
          AND p.persona_id = NEW.persona_id
    ) THEN
        RAISE EXCEPTION 'persona % does not belong to the discussion mode of room %',
            NEW.persona_id, NEW.room_id;
    END IF;

    -- 2. a room has at most one AI persona (FD: room_id, mode_id -> persona_id)
    IF EXISTS (
        SELECT 1
        FROM room_ai_persona x
        WHERE x.room_id = NEW.room_id
          AND x.persona_id <> NEW.persona_id
    ) THEN
        RAISE EXCEPTION 'room % already has an AI persona', NEW.room_id;
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER room_ai_persona_check
    BEFORE INSERT OR UPDATE ON room_ai_persona
    FOR EACH ROW EXECUTE FUNCTION check_room_ai_persona();

-- ----------------------------------------------------------------------------
-- 8. messages -- one chat stream per room. Written by a human OR an AI persona:
--    an exclusive arc, enforced by num_nonnulls. Both FKs are RESTRICT, because
--    SET NULL would break the arc and erase who wrote the message.
-- ----------------------------------------------------------------------------
CREATE TABLE messages (
    message_id      BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id         BIGINT       NOT NULL,
    author_user_id  BIGINT,
    persona_id      BIGINT,
    body            TEXT         NOT NULL,
    sent_at         TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT messages_room_fk
        FOREIGN KEY (room_id) REFERENCES rooms (room_id) ON DELETE CASCADE,
    CONSTRAINT messages_author_fk
        FOREIGN KEY (author_user_id) REFERENCES users (user_id) ON DELETE RESTRICT,
    CONSTRAINT messages_persona_fk
        FOREIGN KEY (persona_id) REFERENCES ai_personas (persona_id) ON DELETE RESTRICT,
    CONSTRAINT messages_exactly_one_author
        CHECK (num_nonnulls(author_user_id, persona_id) = 1),
    CONSTRAINT messages_body_nonblank CHECK (length(btrim(body)) > 0)
);

-- ----------------------------------------------------------------------------
-- 9. video_sessions -- one WebRTC call inside a room.
-- ----------------------------------------------------------------------------
CREATE TABLE video_sessions (
    session_id     BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id        BIGINT       NOT NULL,
    started_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    ended_at       TIMESTAMPTZ,
    recording_url  TEXT,
    CONSTRAINT video_sessions_room_fk
        FOREIGN KEY (room_id) REFERENCES rooms (room_id) ON DELETE CASCADE,
    CONSTRAINT video_sessions_ended_after_started
        CHECK (ended_at IS NULL OR ended_at >= started_at)
);

-- ----------------------------------------------------------------------------
-- 10. video_participants -- M:N between video sessions and users.
-- ----------------------------------------------------------------------------
CREATE TABLE video_participants (
    session_id  BIGINT       NOT NULL,
    user_id     BIGINT       NOT NULL,
    joined_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    left_at     TIMESTAMPTZ,
    CONSTRAINT video_participants_pkey PRIMARY KEY (session_id, user_id),
    CONSTRAINT video_participants_session_fk
        FOREIGN KEY (session_id) REFERENCES video_sessions (session_id) ON DELETE CASCADE,
    CONSTRAINT video_participants_user_fk
        FOREIGN KEY (user_id) REFERENCES users (user_id) ON DELETE CASCADE,
    CONSTRAINT video_participants_left_after_joined
        CHECK (left_at IS NULL OR left_at >= joined_at)
);

-- ----------------------------------------------------------------------------
-- 11. fact_checks -- an AI fact-check attached to one message.
-- ----------------------------------------------------------------------------
CREATE TABLE fact_checks (
    check_id    BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    message_id  BIGINT       NOT NULL,
    persona_id  BIGINT,
    claim_text  TEXT         NOT NULL,
    verdict     VARCHAR(20)  NOT NULL,
    source_url  TEXT,
    checked_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT fact_checks_message_fk
        FOREIGN KEY (message_id) REFERENCES messages (message_id) ON DELETE CASCADE,
    CONSTRAINT fact_checks_persona_fk
        FOREIGN KEY (persona_id) REFERENCES ai_personas (persona_id) ON DELETE SET NULL,
    CONSTRAINT fact_checks_claim_nonblank CHECK (length(btrim(claim_text)) > 0)
);
